import type { NextConfig } from "next";

const dev = process.env.NODE_ENV !== "production";

// Skyddsrubriker på alla svar. Inline-skript tillåts (Next lägger ut sina egna), men allt annat som kan missbrukas är stängt:
// ingen inbäddning i andra sajter, inga plugin, inga formulär eller anrop till andra adresser, ingen rörelse av <base>.
// Teckensnitten hämtas från Google Fonts, därför de två adresserna. Bilder får komma från https (skivomslag från Spotify och Sonos ligger på flera adresser).
const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${dev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "img-src 'self' data: blob: https:",
  "font-src 'self' data: https://fonts.gstatic.com",
  `connect-src 'self'${dev ? " ws: wss:" : ""}`,
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join("; ");

const config: NextConfig = {
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: csp },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=(), usb=()" },
          { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
        ],
      },
      {
        // Familjemedlemmarnas länkar: aldrig i sökmotorer, aldrig i webbläsarens cache av svaret, aldrig vidare som referens.
        source: "/familj/:path*",
        headers: [
          { key: "X-Robots-Tag", value: "noindex, nofollow" },
          { key: "Cache-Control", value: "no-store" },
          { key: "Referrer-Policy", value: "no-referrer" },
        ],
      },
    ];
  },
};

export default config;
